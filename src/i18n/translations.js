/**
 * Returns translation for key or fallback
 */
export function getTranslation(langCode, key, fallback = '') {
  const currentLang = TRANSLATIONS[langCode] || TRANSLATIONS.en;
  if (currentLang && currentLang[key]) {
    return currentLang[key];
  }
  if (TRANSLATIONS.en && TRANSLATIONS.en[key]) {
    return TRANSLATIONS.en[key];
  }
  return fallback || key;
}
